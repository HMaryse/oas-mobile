class Vehicule {
  final int id;
  final String marque;
  final String modele;
  final String immatriculation;
  final int annee;
  final double kilometrage;
  final String numeroChassis;

  const Vehicule({
    required this.id,
    required this.marque,
    required this.modele,
    required this.immatriculation,
    required this.annee,
    required this.kilometrage,
    required this.numeroChassis,
  });
}